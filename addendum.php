    <div class="tp1_title">
        <b>Мой провайдер использует прозрачный прокси. Что делать?</b>
        <a name="proxy"></a>
    </div>

    <div class="tp1_body text">
        <p><i>Примечание: данный раздел носит справочный характер и не является окончательной технической инструкцией.</i></p>
        <br />

        <p>
            Короткий ответ: по возможности смените провайдера на того, который не использует принудительный прокси.
            Если такой возможности нет или вы не хотите менять провайдера, прочитайте информацию ниже.
        </p>
        <br />

        <p><b>Что такое прокси?</b></p>
        <br />

        <p>
            Прокси-сервер — это посредник между вами и сайтом. Когда вы открываете сайт через прокси,
            запрос сначала отправляется на прокси-сервер, а уже затем прокси передаёт его сайту.
            То есть вы подключаетесь не напрямую, а через промежуточный сервер.
        </p>
        <br />

        <p>Существует несколько типов прокси:</p>

        <ul class="treeview">
            <li><b>Прозрачный</b> — не требует настройки у пользователя. Обычно весь HTTP-трафик через порт 80 автоматически перенаправляется через прокси.</li>
            <li><b>Явный / добровольный</b> — пользователь сам указывает прокси в настройках браузера или системы.</li>
            <li><b>Анонимный</b> — прокси не передаёт серверу ваш реальный IP-адрес.</li>
            <li><b>Высокоанонимный</b> — прокси не передаёт ни ваш IP, ни признаки того, что используется прокси.</li>
            <li><b>Публичный</b> — открытый прокси-сервер, доступный разным пользователям.</li>
        </ul>

        <br />

        <p>
            Прозрачный прокси может быть как анонимным, так и неанонимным. Всё зависит от того,
            какие HTTP-заголовки он передаёт сайту.
        </p>
        <br />

        <p><b>Как узнать, нахожусь ли я за прозрачным или анонимным прокси?</b></p>
        <br />

        <p>
            Можно воспользоваться сервисом проверки HTTP-заголовков, например
            <a class="sba" href="http://proxyjudge.org/">ProxyJudge</a>.
            Он показывает, какие данные сервер получает от вашего подключения.
            Важные заголовки: <b>HTTP_CLIENT_IP</b>, <b>HTTP_X_FORWARDED_FOR</b> и <b>REMOTE_ADDR</b>.
        </p>
        <br />

        <p><b>Почему мой порт отображается как «---», хотя я не за NAT и не за файрволом?</b></p>
        <br />

        <p>
            Трекер пытается определить ваш настоящий IP-адрес. Для этого прокси должен передавать заголовок
            <b>HTTP_X_FORWARDED_FOR</b>. Если прокси провайдера этого не делает, трекер может принять IP-адрес
            прокси за ваш настоящий IP.
        </p>
        <br />

        <p>
            В результате при проверке доступности клиента трекер будет пытаться подключиться не к вашему компьютеру,
            а к прокси-серверу провайдера на одном из стандартных BitTorrent-портов. Прокси на этих портах обычно
            не принимает соединения, проверка завершается ошибкой, и трекер считает вас недоступным.
        </p>
        <br />

        <p><b>Можно ли обойти прокси провайдера?</b></p>
        <br />

        <p>
            Если провайдер разрешает только HTTP-трафик через порт 80 или блокирует стандартные прокси-порты,
            может потребоваться SOCKS-прокси или другая схема подключения. Это уже выходит за рамки данного FAQ.
        </p>
        <br />

        <p>В остальных случаях можно попробовать следующее:</p>

        <ul class="treeview">
            <li>Выберите публичный <b>неанонимный</b> прокси, который работает не на порту 80.</li>
            <li>Настройте компьютер или браузер на использование выбранного прокси.</li>
            <li>Проверьте заголовки через ProxyJudge. Если есть <b>HTTP_X_FORWARDED_FOR</b> с вашим IP, всё должно быть нормально.</li>
            <li>Зайдите на трекер и проверьте в профиле, правильно ли определяется ваш IP.</li>
        </ul>

        <br />

        <p>
            Учтите, что публичные прокси обычно работают медленно. Но соединения между пирами не используют порт 80,
            поэтому скорость обмена между клиентами не должна ухудшиться.
        </p>
        <br />

        <p><b>Как заставить BitTorrent-клиент использовать прокси?</b></p>
        <br />

        <p>
            Если прокси настроен на уровне системы, часть программ может использовать эти настройки автоматически.
            Но современные BitTorrent-клиенты обычно имеют отдельные настройки прокси внутри самой программы.
        </p>
        <br />

        <p><b>Относится ли это к другим торрент-сайтам?</b></p>
        <br />

        <p>
            Не обязательно. Разные трекеры могут работать по-разному: одни используют порт 80,
            другие — порт 6969 или собственные настройки. Поэтому эти рекомендации могут не подходить для всех сайтов.
        </p>
    </div>
